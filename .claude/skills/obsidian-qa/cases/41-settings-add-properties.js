const m = document.querySelector("#qa-settings .vertical-tab-content");
const row = (name) => [...m.querySelectorAll(".setting-item")].find((i) => i.offsetParent && i.querySelector(".setting-item-name")?.textContent === name);
const type = (input, v) => { input.value = v; input.dispatchEvent(new Event("input", { bubbles: true })); input.dispatchEvent(new Event("change", { bubbles: true })); };
const idRow = row("Identify tasks by");
out.idRowHtml = idRow.querySelector(".setting-item-control").outerHTML.slice(0, 1500);
out.selects = [...idRow.querySelectorAll("select")].map((x) => ({ visible: !!x.offsetParent, w: x.getBoundingClientRect().width, value: x.value, opts: [...x.options].map((o) => o.textContent) }));
// add properties
const addRow = row("Properties to remind from");
const add = async (name) => { type(addRow.querySelector("input"), name); await sleep(150); addRow.querySelector("button").click(); await sleep(1200); };
await add("visit");
out.afterVisit = JSON.parse(JSON.stringify(s.noteReminderSources.rawValue.value));
ok("D1 adding a property with past values sets the cut-off to today", out.afterVisit.length === 1 && out.afterVisit[0].property === "visit" && out.afterVisit[0].since === day(0) && out.afterVisit[0].managed === false, out.afterVisit);
await add("fresh");
out.afterFresh = JSON.parse(JSON.stringify(s.noteReminderSources.rawValue.value));
ok("D2 a property without past values gets no cut-off", out.afterFresh.find((x) => x.property === "fresh")?.since === "", out.afterFresh);
await add("check");
await add("visit");
ok("D3 adding the same name twice keeps one", s.noteReminderSources.rawValue.value.filter((x) => x.property === "visit").length === 1, s.noteReminderSources.rawValue.value);
await add("  ");
ok("D3 an empty name is not added", s.noteReminderSources.rawValue.value.length === 3, s.noteReminderSources.rawValue.value);
await add("visit-done");
out.afterDoneName = s.noteReminderSources.rawValue.value.map((x) => x.property);
out.noticesAfterAdds = notices();
await sleep(500);
out.blocks = m.innerText.slice(0, m.innerText.indexOf("Show a bell in every note"));
ok("D4 the block tells how many values the cut-off ignores", /2/.test(out.blocks.split("visit")[1] ?? ""), out.blocks);
ok("D5 the block warns about foreign -done values", /check-done/.test(out.blocks), out.blocks);
ok("D6 reminders: only the future visit is read", rems("QA/set/").filter((r) => r.origin.key === "visit").map((r) => r.file).join() === "future.md", rems("QA/set/"));
return finish();
